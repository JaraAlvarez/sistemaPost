CREATE TABLE audit.audit_log (
    id                 uuid          NOT NULL,
    occurred_at        timestamptz   NOT NULL,
    node_id            uuid          NOT NULL,
    seq                bigint        GENERATED BY DEFAULT AS IDENTITY,
    hash_version       smallint      NOT NULL,
    company_id         uuid,
    branch_id          uuid,
    pos_terminal_id    uuid,
    user_id            uuid,
    user_display_name  varchar(120),
    session_id         uuid,
    device_id          uuid,
    ip_address         inet,
    correlation_id     varchar(64),
    module             varchar(30)   NOT NULL,
    action             varchar(60)   NOT NULL,
    entity_type        varchar(60),
    entity_id          uuid,
    entity_label       varchar(200),
    old_values         jsonb,
    new_values         jsonb,
    summary            varchar(500),
    authorized_by      uuid,
    severity           varchar(10)   NOT NULL,
    row_hash           char(64)      NOT NULL,
    CONSTRAINT pk_audit_log PRIMARY KEY (occurred_at, id),
    CONSTRAINT ck_audit_log__action CHECK (action ~ '^[A-Z][A-Z0-9_]+$'),
    CONSTRAINT ck_audit_log__severity CHECK (severity IN ('INFO', 'WARNING', 'CRITICAL')),
    CONSTRAINT ck_audit_log__hash_version CHECK (hash_version > 0),
    CONSTRAINT ck_audit_log__row_hash CHECK (row_hash ~ '^[0-9a-f]{64}$')
