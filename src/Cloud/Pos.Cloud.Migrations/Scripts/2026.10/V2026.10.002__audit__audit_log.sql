CREATE INDEX ix_audit_log__node_seq ON audit.audit_log (node_id, seq, occurred_at);

-- Garantiza que una inserción nunca falle por falta de partición.
CREATE TABLE audit.audit_log_default PARTITION OF audit.audit_log DEFAULT;

-- Crea las particiones mensuales (UTC) desde el mes actual hasta months_ahead meses después.
-- SECURITY DEFINER: pos_app no tiene DDL; el mantenimiento diario la invoca.
-- Si la partición DEFAULT ya tiene filas de ese mes, no se crea (quedan en DEFAULT) y se informa.
CREATE FUNCTION audit.ensure_partitions(months_ahead integer DEFAULT 3) RETURNS integer
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, audit AS $$
DECLARE
    v_start   timestamptz;
    v_end     timestamptz;
    v_name    text;
    v_created integer := 0;
BEGIN
    IF months_ahead < 0 OR months_ahead > 24 THEN
        RAISE EXCEPTION 'months_ahead fuera de rango: %', months_ahead;
    END IF;

    FOR i IN 0..months_ahead LOOP
        v_start := date_trunc('month', now() AT TIME ZONE 'UTC') AT TIME ZONE 'UTC' + make_interval(months => i);
        v_end   := v_start + interval '1 month';
        v_name  := 'audit_log_' || to_char(v_start AT TIME ZONE 'UTC', 'YYYY_MM');

        CONTINUE WHEN EXISTS (
            SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
            WHERE n.nspname = 'audit' AND c.relname = v_name);

        IF EXISTS (SELECT 1 FROM audit.audit_log_default WHERE occurred_at >= v_start AND occurred_at < v_end) THEN
            RAISE NOTICE 'La partición DEFAULT ya contiene filas de %, no se crea %', v_start, v_name;
            CONTINUE;
        END IF;

        EXECUTE format('CREATE TABLE audit.%I PARTITION OF audit.audit_log FOR VALUES FROM (%L) TO (%L)',
                       v_name, v_start, v_end);
        v_created := v_created + 1;
    END LOOP;

    RETURN v_created;
END;
$$;

REVOKE ALL ON FUNCTION audit.ensure_partitions(integer) FROM PUBLIC;

