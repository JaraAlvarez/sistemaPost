-- -----------------------------------------------------------------------------------------------------
-- Sellos: una cadena por nodo. seal_hash = SHA-256 del JCS {v, node_id, seal_no, seq_from, seq_to,
-- rows_count, rows_digest, prev_seal_hash, sealed_at}.
-- -----------------------------------------------------------------------------------------------------
CREATE TABLE audit.audit_seals (
    id              bigint        GENERATED ALWAYS AS IDENTITY,
    node_id         uuid          NOT NULL,
    seal_no         bigint        NOT NULL,
    format_version  smallint      NOT NULL,
    seq_from        bigint        NOT NULL,
    seq_to          bigint        NOT NULL,
    rows_count      integer       NOT NULL,
    rows_digest     char(64)      NOT NULL,
    prev_seal_hash  char(64)      NOT NULL,
    seal_hash       char(64)      NOT NULL,
    sealed_at       timestamptz   NOT NULL,
    CONSTRAINT pk_audit_seals PRIMARY KEY (id),
    CONSTRAINT ux_audit_seals__node_seal_no UNIQUE (node_id, seal_no),
    CONSTRAINT ux_audit_seals__seal_hash UNIQUE (seal_hash),
    CONSTRAINT ck_audit_seals__seal_no CHECK (seal_no > 0),
    CONSTRAINT ck_audit_seals__range CHECK (seq_from > 0 AND seq_to >= seq_from),
    CONSTRAINT ck_audit_seals__rows_count CHECK (rows_count >= 0 AND rows_count <= seq_to - seq_from + 1),
    CONSTRAINT ck_audit_seals__hashes CHECK (
        rows_digest ~ '^[0-9a-f]{64}$' AND prev_seal_hash ~ '^[0-9a-f]{64}$' AND seal_hash ~ '^[0-9a-f]{64}$')
);

-- -----------------------------------------------------------------------------------------------------
-- Append-only: UPDATE/DELETE/TRUNCATE lanzan error incluso para roles con privilegios (defensa adicional
-- a los privilegios: pos_app solo tiene SELECT/INSERT).
-- -----------------------------------------------------------------------------------------------------
CREATE FUNCTION audit.fn_append_only() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'La tabla %.% es de solo inserción', TG_TABLE_SCHEMA, TG_TABLE_NAME
        USING ERRCODE = '42501';
END;
$$;

CREATE TRIGGER trg_audit_log_append_only
    BEFORE UPDATE OR DELETE ON audit.audit_log
    FOR EACH ROW EXECUTE FUNCTION audit.fn_append_only();

CREATE TRIGGER trg_audit_seals_append_only
    BEFORE UPDATE OR DELETE ON audit.audit_seals
    FOR EACH ROW EXECUTE FUNCTION audit.fn_append_only();

CREATE TRIGGER trg_audit_seals_no_truncate
    BEFORE TRUNCATE ON audit.audit_seals
    FOR EACH STATEMENT EXECUTE FUNCTION audit.fn_append_only();
